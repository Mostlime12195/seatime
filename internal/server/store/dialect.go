package store

import (
	"context"
	"database/sql"
	"regexp"
	"strconv"
	"strings"
	"sync"

	_ "github.com/jackc/pgx/v5/stdlib" // database/sql driver "pgx"
)

// The store runs on SQLite or Postgres. Queries are written once, in SQL
// both accept, with '?' placeholders; on Postgres they are rebound to $1,
// $2, ... on the way out (conn and txn below). The schema is the SQLite
// migrations list, translated for Postgres by pgMigration.

// IsPostgres reports whether dsn (SEATIME_DB) names a Postgres database
// rather than a SQLite file.
func IsPostgres(dsn string) bool {
	return strings.HasPrefix(dsn, "postgres://") || strings.HasPrefix(dsn, "postgresql://")
}

var rebound sync.Map // query -> query with $n placeholders

// rebind turns each '?' outside a string literal into $1, $2, ...
func rebind(q string) string {
	if v, ok := rebound.Load(q); ok {
		return v.(string)
	}
	var b strings.Builder
	n, quoted := 0, false
	for i := 0; i < len(q); i++ {
		switch c := q[i]; {
		case c == '\'':
			quoted = !quoted
			b.WriteByte(c)
		case c == '?' && !quoted:
			n++
			b.WriteString("$" + strconv.Itoa(n))
		default:
			b.WriteByte(c)
		}
	}
	rebound.Store(q, b.String())
	return b.String()
}

// conn is the database handle the store queries through: database/sql
// with placeholders rebound on Postgres.
type conn struct {
	raw *sql.DB
	pg  bool
}

func (c *conn) q(query string) string {
	if c.pg {
		return rebind(query)
	}
	return query
}

func (c *conn) ExecContext(ctx context.Context, q string, args ...any) (sql.Result, error) {
	return c.raw.ExecContext(ctx, c.q(q), args...)
}
func (c *conn) QueryContext(ctx context.Context, q string, args ...any) (*sql.Rows, error) {
	return c.raw.QueryContext(ctx, c.q(q), args...)
}
func (c *conn) QueryRowContext(ctx context.Context, q string, args ...any) *sql.Row {
	return c.raw.QueryRowContext(ctx, c.q(q), args...)
}
func (c *conn) PrepareContext(ctx context.Context, q string) (*sql.Stmt, error) {
	return c.raw.PrepareContext(ctx, c.q(q))
}
func (c *conn) BeginTx(ctx context.Context) (*txn, error) {
	tx, err := c.raw.BeginTx(ctx, nil)
	if err != nil {
		return nil, err
	}
	return &txn{tx, c.pg}, nil
}

// txn is a transaction with placeholders rebound on Postgres.
type txn struct {
	tx *sql.Tx
	pg bool
}

func (t *txn) q(query string) string {
	if t.pg {
		return rebind(query)
	}
	return query
}

func (t *txn) ExecContext(ctx context.Context, q string, args ...any) (sql.Result, error) {
	return t.tx.ExecContext(ctx, t.q(q), args...)
}
func (t *txn) QueryContext(ctx context.Context, q string, args ...any) (*sql.Rows, error) {
	return t.tx.QueryContext(ctx, t.q(q), args...)
}
func (t *txn) QueryRowContext(ctx context.Context, q string, args ...any) *sql.Row {
	return t.tx.QueryRowContext(ctx, t.q(q), args...)
}
func (t *txn) PrepareContext(ctx context.Context, q string) (*sql.Stmt, error) {
	return t.tx.PrepareContext(ctx, t.q(q))
}
func (t *txn) Commit() error   { return t.tx.Commit() }
func (t *txn) Rollback() error { return t.tx.Rollback() }

// pgTypes translate a SQLite migration for Postgres. Every integer column
// is BIGINT (unix times in ms do not fit 32 bits) and flags stay 0/1
// integers, so both databases scan into the same Go values; text compares
// and sorts bytewise ("C"), as SQLite's BINARY collation does. Usernames
// lose NOCASE: they are stored lower-case and looked up lower-cased.
var pgTypes = []struct {
	re  *regexp.Regexp
	out string
}{
	{regexp.MustCompile(`\s+WITHOUT ROWID`), ``},
	{regexp.MustCompile(`\s+COLLATE NOCASE`), ``},
	{regexp.MustCompile(`\bid(\s+)INTEGER PRIMARY KEY\b`), `id${1}BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`},
	{regexp.MustCompile(`\bINTEGER\b`), `BIGINT`},
	{regexp.MustCompile(`\bREAL\b`), `DOUBLE PRECISION`},
	{regexp.MustCompile(`\bBLOB\b`), `BYTEA`},
	{regexp.MustCompile(`\bTEXT\b`), `TEXT COLLATE "C"`},
}

// pgMigration is migration m (SQLite) as Postgres runs it. A future
// migration the translation cannot carry needs its own Postgres text here.
func pgMigration(m string) string {
	for _, t := range pgTypes {
		m = t.re.ReplaceAllString(m, t.out)
	}
	return m
}
